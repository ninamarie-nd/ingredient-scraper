"""Build the label scanner into puberty_scanner_embed.html.

Assembles scraper/browser/{scanner.html, scanner.css, scanner.js, grader.js, constants.json}
and the reference table (scraper/ref_compact.json) into one block between
<!-- scanner:start --> and <!-- scanner:end --> markers, placed before </body>.
Run again after editing any source file. Idempotent.
"""
import json, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
HERE = os.path.join(ROOT, 'scraper', 'browser')
PAGE = os.path.join(ROOT, 'puberty_scanner_embed.html')
REF = os.path.join(ROOT, 'scraper', 'ref_compact.json')

def read(p):
    with open(p, encoding='utf-8') as f:
        return f.read()

constants = read(os.path.join(HERE, 'constants.json')).strip()
grader = read(os.path.join(HERE, 'grader.js'))
token = 'var C = __CONSTANTS__;'
if token not in grader:
    sys.exit('grader.js is missing the constants line')
grader = grader.replace(token, 'var C = ' + constants + ';')

ref = json.dumps(json.loads(read(REF)), ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/')

block = '\n'.join([
    '<!-- scanner:start (generated by scraper/browser/build_embed.py; edit the source files, not this block) -->',
    '<style>', read(os.path.join(HERE, 'scanner.css')), '</style>',
    read(os.path.join(HERE, 'scanner.html')),
    '<script id="scanner-ref" type="application/json">' + ref + '</script>',
    '<script>', grader, '</script>',
    '<script>', read(os.path.join(HERE, 'scanner.js')), '</script>',
    '<!-- scanner:end -->',
])

page = read(PAGE)
start, end = '<!-- scanner:start', '<!-- scanner:end -->'
if start in page:
    a = page.index(start)
    b = page.index(end) + len(end)
    page = page[:a] + block + page[b:]
else:
    if page.count('</body>') != 1:
        sys.exit('expected exactly one </body> in the page')
    page = page.replace('</body>', block + '\n</body>')
with open(PAGE, 'w', encoding='utf-8') as f:
    f.write(page)
print('built scanner block:', len(block), 'chars')
